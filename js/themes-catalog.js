export const THEME_IDS = Object.keys(APP_THEMES);

export function applyAppTheme(id) {
  const t = APP_THEMES[id] || APP_THEMES["n3xn-dark"];
  const root = document.documentElement;
  Object.entries(t.vars).forEach(([k, v]) => root.style.setProperty(k, v));
  try {
    localStorage.setItem("n3xn_app_theme", id);
  } catch (_) {}
  try {
    if (window.monaco && t.monaco) {
      // ensure custom themes registered by settings
      window.monaco.editor.setTheme(t.monaco);
    }
  } catch (_) {}
  return t;
}

